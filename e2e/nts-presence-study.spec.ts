import { test, expect } from '@playwright/test';
import { FOUNDATIONAL_SESSION_KEY } from '../src/ui/foundationalOpeningModel';
test('2J semicircle inspection, keyboard slider, bounded field response and evidence', async ({page}) => {
  test.setTimeout(90000);
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(key=>sessionStorage.setItem(key,'seen'),FOUNDATIONAL_SESSION_KEY);
  await page.setViewportSize({width:1440,height:900});await page.goto('/');
  const snapshot=()=>page.evaluate(()=>(() => { const r = window.__MSXAI_STORY_WORLD__!.inspect(); return { state: r.ntsState, scene: "nts" in r ? { ...r, nts: r.nts! } : undefined, ecosystem: r.overviewState, story: r.storyState, locale: document.documentElement.lang, sound: document.querySelector('[data-action="sound"]')?.getAttribute('aria-pressed') === 'true' }; })());
  const settle=()=>expect.poll(async()=>(await snapshot()).scene?.renderLoopActive).toBe(false);
  await page.locator('.entry-card [data-action="living-ecosystem"]').click();await settle();
  await page.evaluate(()=>window.__MSXAI_STORY_WORLD__!.selectNode('nutuensai'));
  await page.locator('[data-ecosystem="visit-nts"]').click();
  await expect.poll(async()=>(await snapshot()).state.phase).toBe('settled');await settle();
  await expect.poll(async()=>(await snapshot()).scene?.nts.loaded).toBe(true);
  await page.locator('[data-nts-memory="s4"]').click();
  await expect.poll(async()=>(await snapshot()).scene?.renderLoopActive).toBe(true);
  await page.waitForTimeout(1100);await page.screenshot({path:'/private/tmp/nts-slice-b-evidence/2j-field-response.png'});
  await settle();await page.screenshot({path:'/private/tmp/nts-slice-b-evidence/2j-gallery.png'});
  const galleryStats=(await snapshot()).scene!;
  console.log('Round 2J settled gallery', JSON.stringify({drawCalls:galleryStats.drawCalls,triangles:galleryStats.triangles,materialCount:galleryStats.materialCount,renderLoopActive:galleryStats.renderLoopActive,textureCount:galleryStats.nts.textureCount}));
  await page.locator('[data-nts="inspect"]').click();await settle();
  await page.screenshot({path:'/private/tmp/nts-slice-b-evidence/2j-front.png'});
  const origin=(await snapshot()).scene!.cameraPosition;
  const slider=page.getByRole('slider');
  const box=(await slider.boundingBox())!;
  await page.mouse.move(box.x+box.width/2,box.y+box.height/2);await page.mouse.down();
  await page.mouse.move(box.x+box.width*.75,box.y+box.height/2,{steps:8});await page.mouse.up();
  await expect.poll(async()=>(await snapshot()).state.inspection).not.toBe('front');
  expect((await snapshot()).state.introduction).toBe(false);
  await slider.focus();await slider.press('End');await settle();
  const right=(await snapshot()).scene!.cameraPosition;
  await page.screenshot({path:'/private/tmp/nts-slice-b-evidence/2j-right-profile.png'});
  await slider.press('Home');await settle();
  const left=(await snapshot()).scene!.cameraPosition;
  expect(Math.hypot(...right.map((v,i)=>v-left[i]))).toBeCloseTo(16,1);
  expect(Math.abs(origin[1]-right[1])).toBeLessThan(.01);
  await page.screenshot({path:'/private/tmp/nts-slice-b-evidence/2j-left-profile.png'});
  await slider.press('ArrowRight');expect((await snapshot()).state.inspection).toBe(-85);
  await slider.fill('45');await settle();await page.screenshot({path:'/private/tmp/nts-slice-b-evidence/2j-three-quarter.png'});
  await page.locator('[data-nts="th"]').click();expect((await snapshot()).state.inspection).toBe(45);
  await page.emulateMedia({reducedMotion:'reduce'});await page.setViewportSize({width:390,height:844});
  await page.locator('[data-angle="front"]').click();await settle();
  await page.screenshot({path:'/private/tmp/nts-slice-b-evidence/2j-portrait-inspection.png'});
  await page.keyboard.press('Escape');await page.locator('[data-nts-memory="s4"]').click();await settle();
  await page.screenshot({path:'/private/tmp/nts-slice-b-evidence/2j-portrait-reduced.png'});
  expect(errors).toEqual([]);
});
